#!/usr/bin/env python3
"""Generate the Polaris SDK's public REST bindings from the vendored API contract."""
import argparse
import json
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "Generated by tools/generate.py. Edit schema/sdk.json or schema/openapi.json."
TARGETS = {
    "zig": {"zig/generated/routes.zig", "zig/generated/models.zig", "sdk/zig/generated.zig"},
    "rust": {"sdk/rust/src/generated.rs"},
    "typescript": {"sdk/typescript/src/generated.ts"},
    "python": {"sdk/python/python/polaris_data/models.py"},
}


def load(name):
    return json.loads((ROOT / "schema" / name).read_text())


def schema_type(spec, lang):
    if spec.get("_sdk_time"):
        return "DataTime"
    if "$ref" in spec:
        return spec["$ref"].split("/")[-1]
    kind = spec.get("type")
    if isinstance(kind, list):
        assert len(kind) == 2 and "null" in kind
        inner = schema_type({**spec, "type": next(t for t in kind if t != "null")}, lang)
        return {"rust": f"Option<{inner}>", "ts": f"{inner} | null", "py": f"Optional[{inner}]"}[lang]
    if kind == "array":
        inner = schema_type(spec["items"], lang)
        return {"rust": f"Vec<{inner}>", "ts": f"Array<{inner}>", "py": f"List[{inner}]"}[lang]
    if kind == "object":
        inner = schema_type(spec.get("additionalProperties", {}), lang)
        return {"rust": f"BTreeMap<String, {inner}>", "ts": f"Record<string, {inner}>", "py": f"Dict[str, {inner}]"}[lang]
    types = {
        "rust": {"integer": "i64", "string": "String", "boolean": "bool", None: "Value"},
        "ts": {"integer": "number", "string": "string", "boolean": "boolean", None: "Json"},
        "py": {"integer": "int", "string": "str", "boolean": "bool", None: "Any"},
    }
    return types[lang][kind]


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def model(name, fields, required, lang):
    output = []
    if lang == "rust":
        default = ", Default" if name in {"DataQuery", "CoverageQuery", "SubscriptionRequest"} else ""
        output += [f"#[derive(Clone, Debug{default}, serde::Serialize, serde::Deserialize)]", f"pub struct {name} {{"]
        for key, spec in fields.items():
            field = snake(key)
            rust_field = f"r#{field}" if field == "type" else field
            ty = schema_type(spec, lang)
            if key not in required and not ty.startswith("Option<"):
                ty = f"Option<{ty}>"
            if key != field:
                output.append(f'    #[serde(rename = "{key}")]')
            output.append(f"    pub {rust_field}: {ty},")
        output.append("}")
    elif lang == "ts":
        output.append(f"export interface {name} {{")
        for key, spec in fields.items():
            optional = "" if key in required else "?"
            ty = schema_type(spec, lang)
            if name == "TableDataMessage" and key == "type":
                ty = json.dumps(spec["example"])
            if name == "CoverageTable" and key == "row_count":
                ty = "number | bigint | null"
            output.append(f"  {key}{optional}: {ty};")
        output.append("}")
    else:
        optional = [key for key in fields if key not in required]
        if optional:
            output.append(f"class _{name}Optional(TypedDict, total=False):")
            output += [f"    {key}: {schema_type(fields[key], lang)}" for key in optional]
            output.append("")
        output.append(f"class {name}({f'_{name}Optional' if optional else 'TypedDict'}):")
        output += [f"    {key}: {schema_type(fields[key], lang)}" for key in fields if key in required] or ["    pass"]
    return output + [""]


def generate():
    spec, overlay = load("openapi.json"), load("sdk.json")
    operations = overlay["operations"]
    schemas = {
        name: (spec["components"]["schemas"][name]["properties"], spec["components"]["schemas"][name].get("required", []))
        for name in overlay["models"]
    }
    routes = [f"// {HEADER}", "", 'pub const Auth = enum { none, optional, required };',
              "pub const Operation = enum { " + ", ".join(op["name"] for op in operations) + " };",
              "", "pub fn route(op: Operation) struct { path: []const u8, auth: Auth, path_key: ?[]const u8, query_keys: []const []const u8 } {",
              "    return switch (op) {"]
    for op in operations:
        operation = spec["paths"][op["path"]]["get"]
        security = operation.get("security")
        auth = "none" if not security else "optional" if {} in security else "required"
        path_key = next((p["name"] for p in operation.get("parameters", []) if p["in"] == "path"), None)
        keys = [p["name"] for p in operation.get("parameters", []) if p["in"] == "query"]
        paths = json.dumps(path_key) if path_key else "null"
        key_code = ", ".join(json.dumps(key) for key in keys)
        routes.append(f'        .{op["name"]} => .{{ .path = "{op["path"]}", .auth = .{auth}, .path_key = {paths}, .query_keys = &.{{ {key_code} }} }},')
        if "query" in op:
            fields = {p["name"]: p["schema"] for p in operation["parameters"]}
            required = [p["name"] for p in operation["parameters"] if p.get("required")]
            if op["name"] == "data":
                fields["filters"] = {"type": "object", "additionalProperties": {"type": "string"}}
                for key in ("start", "end"):
                    fields[key] = {"type": "string", "_sdk_time": True}
            schemas[op["query"]] = fields, required
    routes += ["    };", "}", ""]
    yield "zig/generated/routes.zig", "\n".join(routes)

    rust = [f"// {HEADER}", "", "use serde_json::Value;", "use std::collections::BTreeMap;",
            "use crate::{Client, PolarisError, blocking};", "",
            "#[derive(Clone, Debug, serde::Serialize, serde::Deserialize)]",
            "#[serde(untagged)]", "pub enum DataTime { Text(String), Millis(i64) }", ""]
    ts = [f"// {HEADER}", "", 'import type { Json } from "./types";', "",
          "export type DataTime = string | number;", ""]
    py = [f"# {HEADER}", "", "from typing import Any, Dict, List, Optional, TypedDict, Union", "",
          "DataTime = Union[str, int]", ""]
    for lang, output in (("rust", rust), ("ts", ts), ("py", py)):
        for name, (fields, required) in schemas.items():
            output += model(name, fields, required, lang)

    for async_mode, client in ((True, "Client"), (False, "blocking::PolarisClient")):
        rust.append(f"impl {client} {{")
        for op in operations:
            query = op.get("query")
            args = f", query: {query}" if query else ""
            value = "query" if query else "()"
            name = op["name"]
            response = op["response"] if op["response"] != "Json" else "Value"
            prefix, suffix = ("async ", ".await") if async_mode else ("", "")
            rust += [f"    pub {prefix}fn {name}(&self{args}) -> Result<{response}, PolarisError> {{",
                     f'        self.request("{name}", {value}){suffix}', "    }", ""]
        rust += ["}", ""]

    ts += ["export abstract class GeneratedClient {",
           "  protected abstract request<T>(operation: string, query: object): Promise<T>;", ""]
    py += ["class GeneratedClient:", "    def _request(self, operation: str, query: Any) -> Any:",
           "        raise NotImplementedError", ""]
    zig = [f"// {HEADER}", "", 'const native = @import("polaris_native");',
           'const std = @import("std");', "",
           "pub const Json = std.json.Value;"]
    zig += [f"pub const {name} = native.models.{name};" for name in schemas]
    zig += ["",
           "pub const Client = struct {", "    options: native.Options = .{},", "",
           "    pub fn init(options: native.Options) Client {", "        return .{ .options = options };", "    }", "",
           "    pub const stream = native.openStream;", "    pub const dataRows = native.dataRows;", ""]
    for op in operations:
        name, query = op["name"], op.get("query")
        arg = f"query: {query}" if query else ""
        if name == "coverage":
            arg += " = {}"
        val = "query" if query else "{}"
        ts += [f'  {name}({arg}): Promise<{op["response"]}> {{',
               f'    return this.request("{name}", {val});', "  }", ""]
        arguments, values = [], []
        if query:
            fields, required = schemas[query]
            for key in required:
                arguments.append(f"{key}: {schema_type(fields[key], 'py')}")
                values.append(f'"{key}": {key}')
            optional = [key for key in fields if key not in required]
            if optional:
                arguments.append("*")
            for key in optional:
                arguments.append(f"{key}: Optional[{schema_type(fields[key], 'py')}] = None")
                values.append(f'"{key}": {key}')
        arg = ", " + ", ".join(arguments) if arguments else ""
        response = op["response"] if op["response"] != "Json" else "Dict[str, Any]"
        value = "{" + ", ".join(values) + "}"
        declaration = f"    def {name}(self{arg}) -> {response}:"
        if len(declaration) > 100:
            py += [f"    def {name}(", "        self,"]
            py += [f"        {argument}," for argument in arguments]
            py.append(f"    ) -> {response}:")
        else:
            py.append(declaration)
        invocation = f'        return self._request("{name}", {value})'
        if len(invocation) > 100:
            py += [f'        return self._request("{name}", {{']
            py += [f"            {value}," for value in values]
            py.append("        })")
        else:
            py.append(invocation)
        py.append("")
        arg = f", query: {query}" if query else ""
        val = "query" if query else ".{}"
        name_zig = name
        zig += [f"    pub fn {name_zig}(self: Client, allocator: std.mem.Allocator{arg}) !native.Reply({op['response']}) {{",
                f'        return native.requestAs({op["response"]}, allocator, self.options, .{name}, {val});', "    }", ""]
    ts += ["}", ""]
    zig += ["};", ""]
    yield "sdk/zig/generated.zig", "\n".join(zig)
    zig = [f"// {HEADER}", "", 'const std = @import("std");',
           'const DataTime = @import("../protocol.zig").DataTime;', ""]
    for name, (fields, required) in schemas.items():
        zig.append(f"pub const {name} = struct {{")
        for key, spec in fields.items():
            ty = zig_type(spec)
            if key not in required or ty.startswith("?"):
                ty = (ty if ty.startswith("?") else "?" + ty) + " = null"
            zig_field = '@"type"' if key == "type" else key
            zig.append(f"    {zig_field}: {ty},")
        zig.append("};")
        zig.append("")
    yield "zig/generated/models.zig", "\n".join(zig)
    yield "sdk/rust/src/generated.rs", "\n".join(rust).replace("\n\n}", "\n}")
    yield "sdk/typescript/src/generated.ts", "\n".join(ts).replace("\n\n}", "\n}")
    yield "sdk/python/python/polaris_data/models.py", "\n".join(py)


def zig_type(spec):
    if "$ref" in spec:
        return spec["$ref"].split("/")[-1]
    kind = spec.get("type")
    if spec.get("_sdk_time"):
        return "DataTime"
    if isinstance(kind, list):
        return "?" + zig_type({**spec, "type": next(t for t in kind if t != "null")})
    if kind == "array":
        return "[]const " + zig_type(spec["items"])
    if kind == "object":
        return "std.json.Value"
    return {"integer": "i64", "string": "[]const u8", "boolean": "bool", None: "std.json.Value"}[kind]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--target", action="append", choices=TARGETS,
                        help="generate only this SDK (repeatable, defaults to all)")
    args = parser.parse_args()
    selected = set().union(*(TARGETS[target] for target in args.target or TARGETS))
    stale = []
    for name, source in generate():
        if name not in selected:
            continue
        if name.endswith(".rs"):
            source = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"],
                                    input=source, capture_output=True, check=True, text=True).stdout
        if name.endswith(".zig"):
            source = subprocess.run([os.environ.get("ZIG", "zig"), "fmt", "--stdin"], input=source, capture_output=True,
                                    check=True, text=True).stdout
        path = ROOT / name
        encoded = source.encode("utf8")
        matches = path.is_file() and path.read_bytes() == encoded
        if args.check:
            if not matches:
                stale.append(name)
        elif not matches:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(encoded)
    if stale:
        raise SystemExit("Stale generated files: " + ", ".join(stale))


if __name__ == "__main__":
    main()
